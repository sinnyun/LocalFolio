import type { CatalogState, MaterialOptionItem, MaterialTemplateItem } from './types.js'

const SEED_TS = 1760000000000

function opt(
  id: string,
  category: MaterialOptionItem['category'],
  value: string,
  description: string,
  sortOrder: number,
): MaterialOptionItem {
  return {
    id,
    category,
    label: value,
    value,
    description,
    sortOrder,
    createdAt: SEED_TS,
    updatedAt: SEED_TS,
  }
}

function tpl(
  id: string,
  name: string,
  title: string,
  material: string,
  craft: string,
  size: string,
  quantity: string,
  note: string,
  sortOrder: number,
  showProjectName = false,
): MaterialTemplateItem {
  return {
    id,
    name,
    title,
    material,
    craft,
    size,
    quantity,
    note,
    showProjectName,
    sortOrder,
    createdAt: SEED_TS,
    updatedAt: SEED_TS,
  }
}

