#!/usr/bin/env node
/**
 * Automates `@folio/core-ui-kit` maintenance after `shadcn add`:
 * 1. Rewrites bare `from "cn"` imports in `src/components/ui/*.tsx` to `from "@/lib/utils"`.
 * 2. Strips any global `:root` / `.dark` blocks appended by shadcn CLI to `src/tailwind.css`.
 * 3. Removes accidental `"cn"` runtime dependency from `plugins/core-ui-kit/package.json`.
 * 4. Auto-generates `src/ui-exports.generated.ts` re-exporting every file under
 *    `src/components/ui/*.tsx` and `src/hooks/*.ts`, so adding a shadcn primitive
 *    never requires manually editing `src/client.tsx`.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const uiKitDir = path.join(repoRoot, 'plugins', 'core-ui-kit')
const uiDir = path.join(uiKitDir, 'src', 'components', 'ui')
const hooksDir = path.join(uiKitDir, 'src', 'hooks')
const tailwindCssPath = path.join(uiKitDir, 'src', 'tailwind.css')
const pkgPath = path.join(uiKitDir, 'package.json')
const barrelPath = path.join(uiKitDir, 'src', 'ui-exports.generated.ts')

let fixedImports = 0
if (fs.existsSync(uiDir)) {
  for (const file of fs.readdirSync(uiDir)) {
    if (!file.endsWith('.tsx') && !file.endsWith('.ts')) continue
    const full = path.join(uiDir, file)
    const raw = fs.readFileSync(full, 'utf8')
    if (raw.includes('from "cn"') || raw.includes("from 'cn'")) {
      const next = raw.replace(/from ["']cn["']/g, 'from "@/lib/utils"')
      fs.writeFileSync(full, next, 'utf8')
      fixedImports += 1
    }
  }
}

// Strip global :root / .dark blocks appended by shadcn CLI after our scoped @layer base
if (fs.existsSync(tailwindCssPath)) {
  const raw = fs.readFileSync(tailwindCssPath, 'utf8')
  const marker = '/*\n ---break---\n */\n:root'
  const idx = raw.indexOf(marker)
  if (idx !== -1) {
    fs.writeFileSync(tailwindCssPath, raw.slice(0, idx).trimEnd() + '\n', 'utf8')
  }
}

// Keep core-ui-kit runtime dependencies empty (all UI deps are bundled into lib/client.js)
if (fs.existsSync(pkgPath)) {
  const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'))
  if (pkg.dependencies && Object.keys(pkg.dependencies).length > 0) {
    pkg.devDependencies = { ...(pkg.devDependencies ?? {}) }
    for (const [dep, ver] of Object.entries(pkg.dependencies)) {
      if (dep === 'cn') continue
      if (!pkg.devDependencies[dep]) pkg.devDependencies[dep] = ver
    }
    delete pkg.dependencies
    fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n', 'utf8')
  }
}

// Generate barrel exports for all components/ui/*.tsx and hooks/*.ts
const lines = [
  '// Auto-generated by scripts/sync-ui-kit.mjs — do not edit by hand.',
]

if (fs.existsSync(uiDir)) {
  const uiFiles = fs
    .readdirSync(uiDir)
    .filter(f => f.endsWith('.tsx') || f.endsWith('.ts'))
    .sort()
  for (const file of uiFiles) {
    const base = file.replace(/\.(tsx|ts)$/, '')
    lines.push(`export * from './components/ui/${base}.js'`)
  }
}

if (fs.existsSync(hooksDir)) {
  const hookFiles = fs
    .readdirSync(hooksDir)
    .filter(f => f.endsWith('.ts') || f.endsWith('.tsx'))
    .sort()
  for (const file of hookFiles) {
    const base = file.replace(/\.(tsx|ts)$/, '')
    lines.push(`export * from './hooks/${base}.js'`)
  }
}

const nextBarrel = lines.join('\n') + '\n'
const prevBarrel = fs.existsSync(barrelPath) ? fs.readFileSync(barrelPath, 'utf8') : ''
if (nextBarrel !== prevBarrel) {
  fs.writeFileSync(barrelPath, nextBarrel, 'utf8')
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(
    `ui-kit synced: ${lines.length - 1} modules exported${fixedImports ? `, fixed ${fixedImports} cn imports` : ''}.`,
  )
}
